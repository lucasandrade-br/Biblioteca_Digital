CREATE TABLE genres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE authors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    nationality VARCHAR(80)
);

CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    isbn VARCHAR(13) NOT NULL UNIQUE,
    publisher VARCHAR(120) NOT NULL,
    publication_year INTEGER NOT NULL,
    numero_paginas INTEGER NOT NULL,
    synopsis VARCHAR(2000) NOT NULL,
    cover_url VARCHAR(500),
    genre_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    total_copies INTEGER NOT NULL,
    loaned_copies INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_books_genre FOREIGN KEY (genre_id) REFERENCES genres(id),
    CONSTRAINT ck_books_paginas CHECK (numero_paginas BETWEEN 1 AND 5000),
    CONSTRAINT ck_books_copies CHECK (loaned_copies >= 0 AND loaned_copies <= total_copies)
);

CREATE INDEX idx_books_status_titulo ON books (status, titulo);

CREATE TABLE book_authors (
    book_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    CONSTRAINT pk_book_authors PRIMARY KEY (book_id, author_id),
    CONSTRAINT fk_book_authors_book FOREIGN KEY (book_id) REFERENCES books(id),
    CONSTRAINT fk_book_authors_author FOREIGN KEY (author_id) REFERENCES authors(id)
);
