CREATE TABLE loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reader_id BIGINT NOT NULL,
    book_id BIGINT NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    pickup_code VARCHAR(12) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL,
    requested_at TIMESTAMP WITH TIME ZONE NOT NULL,
    pickup_deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    picked_up_at TIMESTAMP WITH TIME ZONE,
    due_at TIMESTAMP WITH TIME ZONE,
    returned_at TIMESTAMP WITH TIME ZONE,
    renewal_count INTEGER NOT NULL DEFAULT 0,
    fine_in_cents BIGINT NOT NULL DEFAULT 0,
    fine_status VARCHAR(20) NOT NULL,
    fine_paid_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_loans_reader_idempotency UNIQUE (reader_id, idempotency_key),
    CONSTRAINT fk_loans_reader FOREIGN KEY (reader_id) REFERENCES usuarios(id),
    CONSTRAINT fk_loans_book FOREIGN KEY (book_id) REFERENCES books(id)
);

CREATE INDEX idx_loans_reader_requested ON loans (reader_id, requested_at);
CREATE INDEX idx_loans_status_deadline ON loans (status, pickup_deadline);
CREATE INDEX idx_loans_status_due ON loans (status, due_at);
CREATE INDEX idx_loans_book_status ON loans (book_id, status);

CREATE TABLE loan_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id BIGINT NOT NULL,
    type VARCHAR(30) NOT NULL,
    description VARCHAR(255) NOT NULL,
    actor_name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_loan_events_loan FOREIGN KEY (loan_id) REFERENCES loans(id)
);

CREATE INDEX idx_loan_events_loan ON loan_events (loan_id, created_at);

CREATE TABLE fine_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id BIGINT NOT NULL,
    attempt_key VARCHAR(64) NOT NULL UNIQUE,
    provider VARCHAR(20) NOT NULL,
    outcome VARCHAR(20) NOT NULL,
    amount_in_cents BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_fine_payments_loan FOREIGN KEY (loan_id) REFERENCES loans(id)
);

CREATE INDEX idx_fine_payments_loan ON fine_payments (loan_id, created_at);
